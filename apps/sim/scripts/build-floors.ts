// Writes src/world/floors.json: each Strip event's fastest legal run (src/world/core/floorRuns.ts) and the floor the
// server holds a finish to (src/world/floors.ts: that run less FLOOR_MARGIN). Run it again whenever the physics core,
// the old model, the parts, the car table or a track changes; src/world/floors.test.ts says when it is stale.
//   pnpm --filter @micar/sim exec tsx scripts/build-floors.ts        (a few minutes)
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TRACKS } from '../src/world/strip/district';
import { readTrackSync, setTrackDir } from '../src/world/strip/districtNode';
import { fastestRuns, TUNES_TRIED } from '../src/world/core/floorRuns';
import { FLOOR_MARGIN } from '../src/world/floors';

const here = path.dirname(fileURLToPath(import.meta.url));
setTrackDir(path.resolve(here, '../public/strip/tracks'));
for (const t of TRACKS) readTrackSync(t.id);
const runs = fastestRuns(name => process.stderr.write(name + '\n'));
const events: Record<string, { fastest: number; model: string; car: string; tune: Record<string, number>; floor: number }> = {};
for (const r of runs) {
  events[r.eventId] = {
    fastest: Math.round(r.seconds * 1000) / 1000, model: r.model, car: r.car, tune: { ...TUNES_TRIED[r.tune] },
    floor: Math.round(r.seconds * (1 - FLOOR_MARGIN) * 1000) / 1000,
  };
}
const out = { note: 'Generated by scripts/build-floors.ts. Do not edit by hand.', margin: FLOOR_MARGIN, events };
writeFileSync(path.resolve(here, '../src/world/floors.json'), JSON.stringify(out, null, 2) + '\n');
console.log(Object.entries(events).map(([id, e]) => `${id}: fastest ${e.fastest} s (${e.model}, ${e.car}), floor ${e.floor} s`).join('\n'));
